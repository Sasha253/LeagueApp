// Regenerates src/api/schema.d.ts from the backend's OpenAPI schema.
//
// Runs Django's `spectacular` command with the backend virtualenv (make install),
// so no server or database is needed. Set PYTHON to use another interpreter.
// Usage: npm run gen:api

import { execFileSync } from "node:child_process";
import { existsSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";
import ts from "typescript";

const frontendDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const backendDir = resolve(frontendDir, "../backend");
const outFile = join(frontendDir, "src/api/schema.d.ts");

function findPython() {
  if (process.env.PYTHON) return process.env.PYTHON;
  const venv =
    process.platform === "win32"
      ? join(backendDir, ".venv/Scripts/python.exe")
      : join(backendDir, ".venv/bin/python");
  if (existsSync(venv)) return venv;
  throw new Error(`No backend virtualenv at ${venv}. Run \`make install\` or set PYTHON.`);
}

const workDir = mkdtempSync(join(tmpdir(), "leagueapp-openapi-"));
const schemaFile = join(workDir, "schema.yaml");
try {
  execFileSync(
    findPython(),
    ["manage.py", "spectacular", "--validate", "--fail-on-warn", "--file", schemaFile],
    { cwd: backendDir, stdio: "inherit" },
  );
  // Files (format: binary) are Blobs: uploads go in FormData, downloads parse as a blob.
  const blob = ts.factory.createTypeReferenceNode(ts.factory.createIdentifier("Blob"));
  const ast = await openapiTS(pathToFileURL(schemaFile), {
    transform: (schema) => (schema.format === "binary" ? blob : undefined),
  });
  const header =
    "// Generated by `npm run gen:api` from the backend OpenAPI schema. Do not edit.\n\n";
  writeFileSync(outFile, header + astToString(ast));
  console.log(`Wrote ${outFile}`);
} finally {
  rmSync(workDir, { recursive: true, force: true });
}
